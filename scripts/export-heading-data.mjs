// Packs the direction-aware distances downloaded by `bake-heading-seeds.mjs fetch` into src/data/heading-matrix.ts
// so the app can order stops on the phone with the same model the seeds were baked with.
//
// usage: node scripts/export-heading-data.mjs
//
// Layout of the base64 payload (little-endian Uint16, metres, 65535 = no such route / direction):
//   4 tables of N*N   index s*2+t: leave house a facing direction s, arrive at house b facing direction t
//   2 rows of N       library -> house, arriving facing direction t
// N and the order of houses are HEADING_IDS.

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const CACHE = path.join(HERE, ".cache");

const meta = JSON.parse(fs.readFileSync(path.join(CACHE, "heading-matrices.json"), "utf8"));
const raw = fs.readFileSync(path.join(CACHE, "heading-matrices.bin"));
const f = new Float32Array(raw.buffer, raw.byteOffset, raw.byteLength / 4);
const N = meta.ids.length;
if (f.length !== 4 * N * N + 2 * N) throw new Error(`cache holds ${f.length} numbers, expected ${4 * N * N + 2 * N}`);

const subsSrc = fs.readFileSync(path.join(ROOT, "src/data/subscribers.ts"), "utf8");
const ids = [...subsSrc.matchAll(/\{ id: "([^"]+)", routeId: "[^"]+", name: "[^"]*", address: "[^"]+"/g)].map((m) => m[1]);
if (ids.length !== N || ids.some((id, k) => id !== meta.ids[k])) {
  throw new Error("the downloaded distances are for a different list of houses than src/data/subscribers.ts; run `bake-heading-seeds.mjs fetch` again");
}

const out = new Uint16Array(f.length);
let longest = 0;
for (let k = 0; k < f.length; k++) {
  const v = f[k];
  if (!Number.isFinite(v)) { out[k] = 65535; continue; }
  const r = Math.round(v);
  if (r >= 65535) throw new Error(`a distance of ${r} m doesn't fit in 16 bits`);
  out[k] = r;
  if (r > longest) longest = r;
}
const b64 = Buffer.from(out.buffer).toString("base64");
const text = `// Generated by scripts/export-heading-data.mjs from the OSRM distances in scripts/.cache. Do not edit.
// ${N} houses, ${(b64.length / 1048576).toFixed(2)} MB of base64. Layout is described in scripts/export-heading-data.mjs.

export const HEADING_IDS: readonly string[] = ${JSON.stringify(ids)};

export const HEADING_DATA_B64 =
  "${b64}";
`;
fs.writeFileSync(path.join(ROOT, "src/data/heading-matrix.ts"), text);
console.log(`wrote src/data/heading-matrix.ts: ${N} houses, longest leg ${longest} m, ${(text.length / 1048576).toFixed(2)} MB`);
